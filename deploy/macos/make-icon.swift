// Draws lmux's app icon: a dark rounded square with a pixel-art pilot light,
// the flame that stays lit while everything else is off. Writes a 1024px PNG,
// and with --svg also writes the same flame as the site's mark.
//
//   swift deploy/macos/make-icon.swift out.png [--svg deploy/site/lmux-mark.svg]
//
// The flame is the grid below, one character per pixel; the palette maps
// characters to colours. Edit the grid and rerun with --svg so the app icon
// and the site mark stay the same drawing.
import AppKit

let grid = [
    "........y.......",
    ".......yo.......",
    ".......oo.......",
    "......roo.......",
    "..o...rroo......",
    "..rr..rroo....o.",
    "..rro.rrooo..ro.",
    ".drrorrroooo.ro.",
    ".drroorroyoorro.",
    ".drroooroyyooro.",
    "ddrrooooyyyooroo",
    "drroooyyyyyyoorr",
    "drrooyyywyyyoorr",
    "drrooyywwwyyoord",
    "ddrooyywwwwyyord",
    ".drrooywwwwyyord",
    ".ddrooyywwyyoodd",
    "..ddrooyyyyoodd.",
    "...dddrooooddd..",
    ".....dddddd.....",
]
let palette: [Character: UInt32] = [
    "d": 0x8a2410, // ember
    "r": 0xd94320, // lmux orange-red
    "o": 0xf07a3c, // flame
    "y": 0xffc27a, // hot
    "w": 0xfff4e4, // core
]
let burner: UInt32 = 0x4a463c
let cols = grid[0].count, rows = grid.count

func hex(_ v: UInt32) -> String { String(format: "#%06x", v) }
func color(_ v: UInt32, _ a: CGFloat = 1) -> NSColor {
    NSColor(calibratedRed: CGFloat(v >> 16 & 0xff) / 255, green: CGFloat(v >> 8 & 0xff) / 255, blue: CGFloat(v & 0xff) / 255, alpha: a)
}

var args = Array(CommandLine.arguments.dropFirst())
var svgOut: String?
if let i = args.firstIndex(of: "--svg"), i + 1 < args.count { svgOut = args[i + 1]; args.removeSubrange(i...i + 1) }
let out = args.first ?? "icon.png"

// The site mark: one rect per run of same-coloured pixels in a row, plus the
// burner, in grid units so it scales crisply at any size.
if let svgOut {
    var rects = ""
    for (y, row) in grid.enumerated() {
        let cs = Array(row)
        var x = 0
        while x < cols {
            guard let c = palette[cs[x]] else { x += 1; continue }
            var w = 1
            while x + w < cols && cs[x + w] == cs[x] { w += 1 }
            rects += "<rect x=\"\(x)\" y=\"\(y)\" width=\"\(w)\" height=\"1\" fill=\"\(hex(c))\"/>"
            x += w
        }
    }
    rects += "<rect x=\"3\" y=\"\(rows + 1)\" width=\"\(cols - 6)\" height=\"1\" fill=\"\(hex(burner))\" fill-opacity=\".55\"/>"
    let svg = """
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 \(cols) \(rows + 2)" shape-rendering="crispEdges" role="img" aria-label="lmux">
      <!-- Generated by deploy/macos/make-icon.swift; edit the grid there. -->
      \(rects)
    </svg>

    """
    try! svg.write(toFile: svgOut, atomically: true, encoding: .utf8)
}

let size: CGFloat = 1024
let cell: CGFloat = 30
let ox = (size - CGFloat(cols) * cell) / 2   // flame's top-left, y down
let oy: CGFloat = 196

// Fills one grid cell, with y measured down from the top like the grid.
func px(_ x: CGFloat, _ y: CGFloat, _ w: CGFloat = 1, _ h: CGFloat = 1) {
    NSRect(x: ox + x * cell, y: size - (oy + (y + h) * cell), width: w * cell, height: h * cell).fill()
}

// Draw into an exact 1024px bitmap; NSImage.lockFocus would follow the
// screen's backing scale and write 2048px on a Retina Mac.
let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: Int(size), pixelsHigh: Int(size), bitsPerSample: 8,
                           samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .calibratedRGB, bytesPerRow: 0, bitsPerPixel: 0)!
NSGraphicsContext.saveGraphicsState()
NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)

// macOS icon grid: the body is inset ~10% with a continuous-corner radius.
let inset: CGFloat = 100
let body = NSRect(x: inset, y: inset, width: size - 2 * inset, height: size - 2 * inset)
let bodyPath = NSBezierPath(roundedRect: body, xRadius: 185, yRadius: 185)
NSGradient(colors: [color(0x24221d), color(0x12110e)])!.draw(in: bodyPath, angle: -90)

NSGraphicsContext.saveGraphicsState()
bodyPath.addClip()
NSGraphicsContext.current?.shouldAntialias = false

// Warm light on the walls, in stepped pixel rings rather than a smooth blur,
// dithered at each step so the bands read as pixel art.
let cx = CGFloat(cols) / 2, cy = CGFloat(rows) * 0.62
for gy in -8..<(rows + 8) {
    for gx in -8..<(cols + 8) {
        let dx = (CGFloat(gx) + 0.5 - cx) / 1.0, dy = (CGFloat(gy) + 0.5 - cy) / 1.15
        let d = (dx * dx + dy * dy).squareRoot()
        let level = 1 - d / 14
        guard level > 0 else { continue }
        let steps: CGFloat = 4, t = level * steps
        let bayer: [CGFloat] = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5]
        let q = (t.rounded(.down) + (t - t.rounded(.down) > (bayer[(gy & 3) * 4 + (gx & 3)] + 0.5) / 16 ? 1 : 0)) / steps
        guard q > 0 else { continue }
        color(0xd94320, q * 0.2).setFill()
        px(CGFloat(gx), CGFloat(gy))
    }
}

// Sparks drifting up off the flame.
color(0xffc27a).setFill(); px(12, -3); px(3, 0)
color(0xf07a3c, 0.7).setFill(); px(14, 1); px(1, -2)

// The burner the flame sits on.
color(burner).setFill(); px(3, CGFloat(rows) + 1, CGFloat(cols) - 6, 1)
color(0x6a6556).setFill(); px(3, CGFloat(rows) + 1, CGFloat(cols) - 6, 0.34)

// The flame.
for (y, row) in grid.enumerated() {
    for (x, ch) in row.enumerated() {
        guard let c = palette[ch] else { continue }
        color(c).setFill()
        px(CGFloat(x), CGFloat(y))
    }
}
NSGraphicsContext.restoreGraphicsState()

NSGraphicsContext.current?.shouldAntialias = true
NSColor(white: 1, alpha: 0.07).setStroke()
bodyPath.lineWidth = 6
bodyPath.stroke()

NSGraphicsContext.restoreGraphicsState()
try! rep.representation(using: .png, properties: [:])!.write(to: URL(fileURLWithPath: out))
